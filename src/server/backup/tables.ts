export type BackupFingerprint = { v: number; tables: Record<string, Record<string, ColumnRule>> };

// Compared with tests/fixtures/backup/columns-v<v>.json: changing what an archive holds without
// raising the version fails there.
export function backupColumnsFingerprint(tables = BACKUP_TABLES): BackupFingerprint {
  return {
    v: BACKUP_VERSION,
    tables: Object.fromEntries(
      tables.map((entry) => [
        entry.name,
        Object.fromEntries(
          Object.entries(entry.columns).sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0)),
        ),
      ]),
    ),
  };
}

export function backupColumnsHash(tables = BACKUP_TABLES): string {
  return createHash("sha256")
    .update(JSON.stringify(backupColumnsFingerprint(tables)))
    .digest("hex");
}

// The tables an archive of version `v` holds, every one of them, even when empty.
export function tablesOfVersion(v: number): BackupTable[] {
  return BACKUP_TABLES.filter((entry) => (entry.since ?? 1) <= v);
}
