export function textLimit(table: string, column: string): number | undefined {
  const key = `${table}.${column}`;
  return Object.hasOwn(TEXT_LIMITS, key) ? TEXT_LIMITS[key] : undefined;
}

// For the app's own messages and keys, which it builds rather than takes from a form.
export function fitText(table: string, column: string, value: string): string {
  const limit = textLimit(table, column);
  return limit === undefined || value.length <= limit ? value : value.slice(0, limit);
}
